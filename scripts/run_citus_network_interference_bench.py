#!/usr/bin/env python3
"""Run a Citus pgbench benchmark while background network traffic is active.

The foreground workload is a fixed pgbench run at a chosen client concurrency.
Background traffic is generated by separate worker and writer loops that run
large distributed COPY/SELECT batches until a shared stop time so the overlap
with pgbench is guaranteed by construction.
"""

from __future__ import annotations

import argparse
import csv
import importlib.util
import json
import shlex
import subprocess
import sys
import threading
import time
from dataclasses import dataclass
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[1]
REPORT_HELPER = REPO_ROOT / "scripts" / "pgbench_report.py"


def load_report_helper():
    """Load the shared pgbench parsing helpers from the report script."""
    spec = importlib.util.spec_from_file_location("pgbench_report", REPORT_HELPER)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"could not load report helper from {REPORT_HELPER}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


REPORT = load_report_helper()
ARCHIVE_SERVER_LOGS = REPO_ROOT / "scripts" / "archive_server_logs.py"
RESET_SERVER_LOGS = REPO_ROOT / "scripts" / "reset_server_logs.py"

SERVER_LOG_NODES = ("node-0", "node-1", "node-2")
BACKGROUND_READ_PREFIX_DEFAULT = "bg_read_src"
BACKGROUND_WRITE_PREFIX_DEFAULT = "bg_write_sink"
PRIVATE_TABLE_PREFIX_DEFAULT = "pgbench_private_accounts"


def run_cmd(
    args: list[str],
    *,
    input_text: str | None = None,
    stdout=None,
    stderr=None,
) -> subprocess.CompletedProcess[str]:
    """Run a command and raise immediately on failure."""
    return subprocess.run(
        args,
        check=True,
        text=True,
        input=input_text,
        stdout=stdout,
        stderr=stderr,
    )


def is_too_many_clients_error(exc: subprocess.CalledProcessError) -> bool:
    """Return True when a subprocess failure is just connection pressure."""

    combined = ""
    if exc.stdout:
        combined += exc.stdout
    if exc.stderr:
        combined += exc.stderr
    return "too many clients already" in combined.lower()


def ssh_cmd(
    node: str,
    remote_cmd: str,
    *,
    input_text: str | None = None,
    stdout=None,
    stderr=None,
) -> subprocess.CompletedProcess[str]:
    """Run a shell command on a remote node via SSH."""
    return run_cmd(
        ["ssh", "-o", "BatchMode=yes", node, remote_cmd],
        input_text=input_text,
        stdout=stdout,
        stderr=stderr,
    )


def psql_cmd(host: str, dbname: str, sql: str, *, input_text: str | None = None, stdout=None) -> subprocess.CompletedProcess[str]:
    """Run a single psql command against the local coordinator."""
    return run_cmd(
        [
            str(Path.home() / "pg" / "bin" / "psql"),
            "-v",
            "ON_ERROR_STOP=1",
            "-X",
            "-Atq",
            "-h",
            host,
            "-p",
            "5432",
            "-U",
            "JasonHu",
            "-d",
            dbname,
            "-c",
            sql,
        ],
        input_text=input_text,
        stdout=stdout,
        stderr=subprocess.PIPE,
    )


def set_system_setting_local(setting: str, value: str) -> None:
    """Set a runtime GUC on the local coordinator node and reload."""
    psql_cmd("127.0.0.1", "postgres", f"ALTER SYSTEM SET {setting} = '{value}';")
    run_cmd([str(Path.home() / "pg" / "bin" / "pg_ctl"), "reload", "-D", str(Path.home() / "pg" / "data")])


def set_system_setting_remote(node: str, setting: str, value: str) -> None:
    """Set a runtime GUC on a remote node and reload that server."""
    remote_cmd = (
        f"set -e; "
        f"$HOME/pg/bin/psql -v ON_ERROR_STOP=1 -X -d postgres -c \"ALTER SYSTEM SET {setting} = '{value}';\"; "
        f"$HOME/pg/bin/pg_ctl reload -D $HOME/pg/data"
    )
    ssh_cmd(node, remote_cmd)


def sql_identifier(name: str) -> str:
    """Quote a SQL identifier for direct embedding in generated SQL."""
    return '"' + name.replace('"', '""') + '"'


def sql_literal(value: str) -> str:
    """Quote a SQL string literal for direct embedding in generated SQL."""
    return "'" + value.replace("'", "''") + "'"


def background_table_name(prefix: str, session_id: int, total_sessions: int) -> str:
    """Return the stable table name for one background session."""
    width = max(2, len(str(max(total_sessions - 1, 0))))
    return f"{prefix}_{session_id:0{width}d}"


def background_table_names(prefix: str, total_sessions: int) -> list[str]:
    """Return all per-session table names for a prefix."""
    return [background_table_name(prefix, session_id, total_sessions) for session_id in range(total_sessions)]


def reset_server_logs() -> None:
    """Rotate and prune the collector logs before the next benchmark row."""
    run_cmd(
        [
            sys.executable,
            str(RESET_SERVER_LOGS),
            "--nodes",
            *SERVER_LOG_NODES,
        ]
    )


def archive_server_logs(run_dir: Path) -> None:
    """Copy the row-local collector suffix from each node.

    The benchmark runner records a row-start snapshot before the workload
    begins. Use that snapshot here so we only archive the bytes written during
    the benchmark row, instead of replaying the whole collector directory.
    """
    baseline_path = run_dir / "server-log-baseline.json"
    run_cmd(
        [
            sys.executable,
            str(ARCHIVE_SERVER_LOGS),
            "--output-dir",
            str(run_dir / "server-logs"),
            "--baseline-json",
            str(baseline_path),
            "--nodes",
            *SERVER_LOG_NODES,
        ]
    )


def snapshot_server_log_baseline(run_dir: Path, nodes: tuple[str, ...]) -> None:
    """Record the active collector logfile and byte offset for each node."""

    baseline: list[dict[str, int | str]] = []
    snapshot_cmd = (
        "set -e; "
        "export PATH=$HOME/pg/bin:$PATH; "
        "logfile=$($HOME/pg/bin/psql -Atq -X -d postgres -c \"SELECT pg_current_logfile();\"); "
        "if [ -z \"$logfile\" ]; then exit 1; fi; "
        "abs_path=$HOME/pg/data/$logfile; "
        "offset=$(stat -c %s \"$abs_path\"); "
        "printf '%s\\t%s\\n' \"$abs_path\" \"$offset\""
    )

    for node in nodes:
        deadline = time.monotonic() + 10.0
        while True:
            try:
                result = ssh_cmd(node, snapshot_cmd, stdout=subprocess.PIPE)
                parts = result.stdout.strip().split("\t")
                if len(parts) != 2:
                    raise RuntimeError(f"could not capture logfile snapshot on {node}: {result.stdout!r}")
                source_path, size_text = parts
                baseline.append(
                    {
                        "node": node,
                        "source_path": source_path,
                        "start_offset_bytes": int(size_text),
                    }
                )
                break
            except subprocess.CalledProcessError as exc:
                if not is_too_many_clients_error(exc) or time.monotonic() >= deadline:
                    raise
                time.sleep(0.2)

    (run_dir / "server-log-baseline.json").write_text(
        json.dumps(baseline, indent=2, sort_keys=True),
        encoding="utf-8",
    )


def finalize_server_logs_for_archive(nodes: tuple[str, ...]) -> None:
    """Force collector-visible row boundaries before archiving.

    The end marker leaves a logical fence in the logs, but the collector can
    still be draining the active segment when we start copying files. Rotating
    here moves the row tail into a durable segment before the archive snapshot.
    """

    remote_cmd = (
        "export PATH=$HOME/pg/bin:$PATH; "
        "psql -v ON_ERROR_STOP=1 -X -d postgres -c 'SELECT pg_rotate_logfile();'"
    )
    for node in nodes:
        ssh_cmd(node, remote_cmd)

    time.sleep(0.5)


def emit_row_log_marker(
    *, mode: str, level: int, clients: int, repeat: int, phase: str, nodes: tuple[str, ...]
) -> None:
    """Emit one explicit LOG line on each node around one interference row.

    The start marker materializes the fresh collector segment before the row
    begins. The end marker leaves a final collector entry behind before
    archival.
    """

    message = (
        f"pgbench row marker phase={phase} mode={mode} "
        f"background_level={level} clients={clients} repeat={repeat}"
    )
    sql = f"DO $$ BEGIN RAISE LOG {message!r}; END $$;"
    remote_cmd = (
        "export PATH=$HOME/pg/bin:$PATH; "
        f"psql -v ON_ERROR_STOP=1 -X -d postgres -c {shlex.quote(sql)}"
    )
    for node in nodes:
        ssh_cmd(node, remote_cmd)


def set_synchronous_commit(mode: str) -> None:
    """Apply synchronous_commit locally on the coordinator and reload."""
    set_system_setting_local("synchronous_commit", mode)
    for node in ("node-1", "node-2", "node-3", "node-4"):
        try:
            set_system_setting_remote(node, "synchronous_commit", mode)
        except Exception as exc:  # pragma: no cover - defensive cluster drift path
            print(f"warning: could not set synchronous_commit={mode} on {node}: {exc}", file=sys.stderr)


def configure_synchronous_standbys() -> None:
    """Make the worker primaries wait for their physical standbys."""
    set_system_setting_remote("node-1", "synchronous_standby_names", "FIRST 1 (worker1_stby)")
    set_system_setting_remote("node-2", "synchronous_standby_names", "FIRST 1 (worker2_stby)")


def collect_metrics(
    summary_paths: list[Path],
    log_prefixes: list[Path],
    sampling_rate: float,
) -> dict[str, float | int]:
    """Parse one or more pgbench summaries and logs into one metrics dict."""
    summaries = [
        REPORT.parse_summary(path.read_text(encoding="utf-8", errors="replace"))
        for path in summary_paths
    ]

    log_paths: list[Path] = []
    for log_prefix in log_prefixes:
        log_paths.extend(sorted(log_prefix.parent.glob(f"{log_prefix.name}*")))
    times_us, non_numeric, total_lines = REPORT.load_log_times(log_paths)
    if not times_us:
        prefixes = ", ".join(str(prefix) for prefix in log_prefixes)
        raise RuntimeError(f"no transaction samples were found for {prefixes}")

    processed_values = [summary.processed for summary in summaries if summary.processed is not None]
    failed_values = [summary.failed for summary in summaries if summary.failed is not None]
    tps_values = [summary.tps for summary in summaries if summary.tps is not None]
    latency_inputs = [
        (summary.processed, summary.latency_avg_ms)
        for summary in summaries
        if summary.processed is not None and summary.latency_avg_ms is not None
    ]
    stddev_inputs = [
        (summary.processed, summary.latency_stddev_ms)
        for summary in summaries
        if summary.processed is not None and summary.latency_stddev_ms is not None
    ]
    latency_weight = sum(processed for processed, _ in latency_inputs)
    stddev_weight = sum(processed for processed, _ in stddev_inputs)

    metrics: dict[str, float | int] = {
        "transactions_processed": sum(processed_values) if processed_values else -1,
        "failed_transactions": sum(failed_values) if failed_values else -1,
        "latency_avg_ms": (
            sum(processed * latency for processed, latency in latency_inputs) / latency_weight
            if latency_weight
            else -1.0
        ),
        "latency_stddev_ms": (
            sum(processed * stddev for processed, stddev in stddev_inputs) / stddev_weight
            if stddev_weight
            else -1.0
        ),
        "throughput_tps": sum(tps_values) if tps_values else -1.0,
        "sampled_transactions": len(times_us),
        "total_log_lines": total_lines,
        "non_numeric_log_entries": non_numeric,
        "p50_ms": REPORT.percentile_nearest_rank(times_us, 50.0) / 1000.0,
        "p95_ms": REPORT.percentile_nearest_rank(times_us, 95.0) / 1000.0,
        "p99_ms": REPORT.percentile_nearest_rank(times_us, 99.0) / 1000.0,
        "min_ms": min(times_us) / 1000.0,
        "max_ms": max(times_us) / 1000.0,
    }
    if sampling_rate > 0:
        metrics["estimated_total_transactions"] = round(len(times_us) / sampling_rate)
    else:
        metrics["estimated_total_transactions"] = -1
    return metrics


def write_client_private_script(script_path: Path, table_name: str) -> None:
    """Write a pgbench script that only touches one client's private table."""
    quoted_table = sql_identifier(table_name)
    script_path.write_text(
        "\n".join(
            [
                "\\set aid random(1, :client_private_rows)",
                "\\set delta random(-5000, 5000)",
                "BEGIN;",
                f"UPDATE {quoted_table} SET abalance = abalance + :delta WHERE aid = :aid;",
                f"SELECT abalance FROM {quoted_table} WHERE aid = :aid;",
                "END;",
                "",
            ]
        ),
        encoding="utf-8",
    )


def workload_run_dir(
    base_dir: Path,
    workload: str,
    mode: str,
    clients: int,
    level: int,
    repeat: int,
) -> Path:
    """Return a stable per-row result directory."""
    return base_dir / workload / mode / f"c{clients:02d}" / f"b{level:02d}" / f"r{repeat:02d}"


def run_pgbench(
    *,
    clients: int,
    worker_threads: int,
    duration_s: int,
    dbname: str,
    sample_rate: float,
    mode: str,
    query_mode: str,
    workload: str,
    private_table_prefix: str,
    client_private_rows: int,
    run_dir: Path,
) -> dict[str, float | int]:
    """Execute one pgbench run and return the parsed metrics."""
    run_dir.mkdir(parents=True, exist_ok=True)
    pgbench_bin = Path.home() / "pg" / "bin" / "pgbench"
    summary_paths: list[Path] = []
    log_prefixes: list[Path] = []

    if workload == "tpcb":
        summary_path = run_dir / "pgbench.out"
        log_prefix = run_dir / "pgbench_log"
        threads = min(worker_threads, clients)
        cmd = [
            str(pgbench_bin),
            "-U",
            "JasonHu",
            "-h",
            "127.0.0.1",
            "-p",
            "5432",
            "-c",
            str(clients),
            "-j",
            str(threads),
            "-M",
            query_mode,
            "-T",
            str(duration_s),
            "-l",
            "--log-prefix",
            str(log_prefix),
        ]
        if sample_rate != 1.0:
            cmd.extend(["--sampling-rate", str(sample_rate)])
        cmd.append(dbname)

        print(
            f"running workload={workload} mode={mode} clients={clients} "
            f"threads={threads} duration={duration_s}s",
            flush=True,
        )
        with summary_path.open("w", encoding="utf-8") as summary_file:
            subprocess.run(
                cmd,
                stdout=summary_file,
                stderr=subprocess.STDOUT,
                text=True,
                check=True,
            )
        summary_paths.append(summary_path)
        log_prefixes.append(log_prefix)
    elif workload == "client-private-table":
        threads = clients
        processes: list[tuple[int, subprocess.Popen[str], object]] = []
        print(
            f"running workload={workload} mode={mode} clients={clients} "
            f"processes={clients} duration={duration_s}s",
            flush=True,
        )
        for client_id in range(clients):
            table_name = f"{private_table_prefix}_{client_id:02d}"
            script_path = run_dir / f"client_{client_id:02d}.sql"
            summary_path = run_dir / f"pgbench_client_{client_id:02d}.out"
            log_prefix = run_dir / f"pgbench_log_client_{client_id:02d}"
            write_client_private_script(script_path, table_name)
            cmd = [
                str(pgbench_bin),
                "-U",
                "JasonHu",
                "-h",
                "127.0.0.1",
                "-p",
                "5432",
                "-c",
                "1",
                "-j",
                "1",
                "-M",
                query_mode,
                "-T",
                str(duration_s),
                "-D",
                f"client_private_rows={client_private_rows}",
                "-f",
                str(script_path),
                "-l",
                "--log-prefix",
                str(log_prefix),
            ]
            if sample_rate != 1.0:
                cmd.extend(["--sampling-rate", str(sample_rate)])
            cmd.append(dbname)
            summary_file = summary_path.open("w", encoding="utf-8")
            process = subprocess.Popen(
                cmd,
                stdout=summary_file,
                stderr=subprocess.STDOUT,
                text=True,
            )
            processes.append((client_id, process, summary_file))
            summary_paths.append(summary_path)
            log_prefixes.append(log_prefix)

        failures: list[str] = []
        for client_id, process, summary_file in processes:
            return_code = process.wait()
            summary_file.close()
            if return_code != 0:
                failures.append(f"client {client_id} exited with status {return_code}")
        if failures:
            raise RuntimeError("; ".join(failures))
    else:
        raise ValueError(f"unsupported workload: {workload}")

    metrics = collect_metrics(summary_paths, log_prefixes, sample_rate)
    metrics["mode"] = mode
    metrics["query_mode"] = query_mode
    metrics["workload"] = workload
    metrics["clients"] = clients
    metrics["threads"] = threads
    metrics["duration_s"] = duration_s
    metrics["sampling_rate"] = sample_rate
    metrics["server_logs_dir"] = str(run_dir / "server-logs")

    print(
        "  done: "
        f"tps={metrics['throughput_tps']:.3f} "
        f"p50={metrics['p50_ms']:.3f}ms "
        f"p99={metrics['p99_ms']:.3f}ms",
        flush=True,
    )

    return metrics


def table_exists(dbname: str, table_name: str) -> bool:
    """Return True when a table exists in the benchmark database."""
    result = psql_cmd(
        "127.0.0.1",
        dbname,
        f"SELECT to_regclass({sql_literal(table_name)}) IS NOT NULL;",
        stdout=subprocess.PIPE,
    )
    return result.stdout.strip() == "t"


def table_persistence(dbname: str, table_name: str) -> str:
    """Return the relation persistence flag for a table."""
    result = psql_cmd(
        "127.0.0.1",
        dbname,
        f"SELECT relpersistence FROM pg_class WHERE oid = {sql_literal(table_name)}::regclass;",
        stdout=subprocess.PIPE,
    )
    return result.stdout.strip()


def table_row_count(dbname: str, table_name: str) -> int:
    """Return the current row count for a table."""
    result = psql_cmd("127.0.0.1", dbname, f"SELECT count(*) FROM {sql_identifier(table_name)};", stdout=subprocess.PIPE)
    return int(result.stdout.strip() or "0")


def ensure_ready(
    dbname: str,
    *,
    background_read_prefix: str,
    background_write_prefix: str,
    background_max_sessions: int,
    background_tables_logged: bool,
) -> None:
    """Verify that the benchmark tables and background tables exist."""
    preload = psql_cmd("127.0.0.1", "postgres", "SHOW shared_preload_libraries;", stdout=subprocess.PIPE)
    if "citus" not in preload.stdout:
        raise RuntimeError(
            "node-0 does not currently preload citus. Run scripts/setup_citus_network_interference.py first."
        )

    pgbench_check = (
        "SELECT count(*) FROM pg_dist_partition "
        "WHERE logicalrelid IN ('pgbench_accounts'::regclass, 'pgbench_branches'::regclass, "
        "'pgbench_tellers'::regclass, 'pgbench_history'::regclass);"
    )
    pgbench_result = psql_cmd("127.0.0.1", dbname, pgbench_check, stdout=subprocess.PIPE)
    if int(pgbench_result.stdout.strip() or "0") != 4:
        raise RuntimeError(
            f"expected 4 distributed pgbench tables in {dbname}. "
            "Run scripts/setup_citus_network_interference.py first."
        )

    expected_persistence = "p" if background_tables_logged else "u"
    for session_id in range(background_max_sessions):
        read_table = background_table_name(background_read_prefix, session_id, background_max_sessions)
        write_table = background_table_name(background_write_prefix, session_id, background_max_sessions)

        for table_name, expected_rows in ((read_table, 1), (write_table, 0)):
            if not table_exists(dbname, table_name):
                raise RuntimeError(
                    f"expected background table {table_name} in {dbname}. "
                    "Run scripts/setup_citus_network_interference.py first."
                )

            distributed = psql_cmd(
                "127.0.0.1",
                dbname,
                f"SELECT count(*) FROM pg_dist_partition WHERE logicalrelid = {sql_literal(table_name)}::regclass;",
                stdout=subprocess.PIPE,
            )
            if int(distributed.stdout.strip() or "0") != 1:
                raise RuntimeError(
                    f"expected background table {table_name} to be distributed on node-0. "
                    "Run scripts/setup_citus_network_interference.py first."
                )

            persistence = table_persistence(dbname, table_name)
            if persistence != expected_persistence:
                raise RuntimeError(
                    f"expected background table {table_name} to be "
                    f"{'logged' if background_tables_logged else 'unlogged'} "
                    f"but relpersistence was {persistence!r}"
                )

            row_count = table_row_count(dbname, table_name)
            if expected_rows == 1 and row_count < 1:
                raise RuntimeError(
                    f"expected background read table {table_name} to contain data, found {row_count} rows"
                )
            if expected_rows == 0 and row_count != 0:
                raise RuntimeError(
                    f"expected background write table {table_name} to be empty before the run, found {row_count} rows"
                )

    worker1 = ssh_cmd(
        "node-1",
        (
            "$HOME/pg/bin/psql -Atq -h 127.0.0.1 -p 5432 -U JasonHu -d postgres "
            "-c \"SELECT count(*) FROM pg_stat_replication WHERE application_name = 'worker1_stby' AND state = 'streaming';\""
        ),
        stdout=subprocess.PIPE,
    )
    worker2 = ssh_cmd(
        "node-2",
        (
            "$HOME/pg/bin/psql -Atq -h 127.0.0.1 -p 5432 -U JasonHu -d postgres "
            "-c \"SELECT count(*) FROM pg_stat_replication WHERE application_name = 'worker2_stby' AND state = 'streaming';\""
        ),
        stdout=subprocess.PIPE,
    )
    if int(worker1.stdout.strip() or "0") != 1 or int(worker2.stdout.strip() or "0") != 1:
        raise RuntimeError(
            "expected both worker standbys to be streaming from their primaries. "
            "Run scripts/setup_citus_network_interference.py first."
        )


def make_writer_batch(rows: int, payload_bytes: int, *, session_id: int, batch_id: int) -> str:
    """Generate a CSV batch for the COPY writer workload."""
    payload = "x" * payload_bytes
    base_id = session_id * 10_000_000_000 + batch_id * rows
    lines = [f"{base_id + i},{payload}" for i in range(rows)]
    return "\n".join(lines) + "\n"


@dataclass
class BackgroundStats:
    role: str
    sessions: int
    batches: int = 0
    errors: list[str] = None

    def __post_init__(self) -> None:
        if self.errors is None:
            self.errors = []


def reader_worker(
    *,
    session_id: int,
    start_at: float,
    stop_at: float,
    dbname: str,
    source_table: str,
    stats: BackgroundStats,
    failure_event: threading.Event,
) -> None:
    """Continuously stream a large distributed table to /dev/null until stop_at."""
    pgbench_bin = Path.home() / "pg" / "bin" / "psql"
    try:
        while time.monotonic() < start_at:
            time.sleep(min(0.2, start_at - time.monotonic()))
        while time.monotonic() < stop_at and not failure_event.is_set():
            cmd = [
                str(pgbench_bin),
                "-v",
                "ON_ERROR_STOP=1",
                "-X",
                "-q",
                "-h",
                "127.0.0.1",
                "-p",
                "5432",
                "-U",
                "JasonHu",
                "-d",
                dbname,
                "-c",
                f"COPY (SELECT * FROM {sql_identifier(source_table)}) TO STDOUT;",
            ]
            try:
                run_cmd(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)
                stats.batches += 1
            except subprocess.CalledProcessError as exc:
                if not is_too_many_clients_error(exc):
                    raise
                # The high-interference case can transiently exhaust server
                # slots. Back off briefly and retry until the row deadline.
                time.sleep(0.2)
    except Exception as exc:  # pragma: no cover - benchmark control path
        stats.errors.append(f"reader-{session_id}({source_table}): {exc}")
        failure_event.set()


def writer_worker(
    *,
    session_id: int,
    start_at: float,
    stop_at: float,
    dbname: str,
    sink_table: str,
    batch_rows: int,
    payload_bytes: int,
    stats: BackgroundStats,
    failure_event: threading.Event,
) -> None:
    """Continuously COPY rows into the distributed sink until stop_at."""
    psql_bin = Path.home() / "pg" / "bin" / "psql"
    batch_id = 0
    try:
        batch_input = make_writer_batch(batch_rows, payload_bytes, session_id=session_id, batch_id=0)
        while time.monotonic() < start_at:
            time.sleep(min(0.2, start_at - time.monotonic()))
        while time.monotonic() < stop_at and not failure_event.is_set():
            cmd = [
                str(psql_bin),
                "-v",
                "ON_ERROR_STOP=1",
                "-X",
                "-q",
                "-h",
                "127.0.0.1",
                "-p",
                "5432",
                "-U",
                "JasonHu",
                "-d",
                dbname,
                "-c",
                f"COPY {sql_identifier(sink_table)} (id, payload) FROM STDIN WITH (FORMAT csv);",
            ]
            try:
                run_cmd(cmd, input_text=batch_input, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)
                stats.batches += 1
            except subprocess.CalledProcessError as exc:
                if not is_too_many_clients_error(exc):
                    raise
                # Back off instead of failing the whole benchmark when the
                # cluster briefly has no free client slots.
                time.sleep(0.2)
                continue
            batch_id += 1
            batch_input = make_writer_batch(batch_rows, payload_bytes, session_id=session_id, batch_id=batch_id)
    except Exception as exc:  # pragma: no cover - benchmark control path
        stats.errors.append(f"writer-{session_id}({sink_table}): {exc}")
        failure_event.set()


def launch_reader_thread(
    *,
    barrier: threading.Barrier,
    session_id: int,
    start_at: float,
    stop_at: float,
    dbname: str,
    source_table: str,
    stats: BackgroundStats,
    failure_event: threading.Event,
) -> None:
    """Wait for the launch barrier and then run one reader loop."""
    barrier.wait()
    reader_worker(
        session_id=session_id,
        start_at=start_at,
        stop_at=stop_at,
        dbname=dbname,
        source_table=source_table,
        stats=stats,
        failure_event=failure_event,
    )


def launch_writer_thread(
    *,
    barrier: threading.Barrier,
    session_id: int,
    start_at: float,
    stop_at: float,
    dbname: str,
    sink_table: str,
    batch_rows: int,
    payload_bytes: int,
    stats: BackgroundStats,
    failure_event: threading.Event,
) -> None:
    """Wait for the launch barrier and then run one writer loop."""
    barrier.wait()
    writer_worker(
        session_id=session_id,
        start_at=start_at,
        stop_at=stop_at,
        dbname=dbname,
        sink_table=sink_table,
        batch_rows=batch_rows,
        payload_bytes=payload_bytes,
        stats=stats,
        failure_event=failure_event,
    )


def truncate_background_write_tables(dbname: str, table_names: list[str]) -> None:
    """Reset background write sinks so each measured row starts clean."""
    if not table_names:
        return
    quoted_tables = ", ".join(sql_identifier(table_name) for table_name in table_names)
    psql_cmd("127.0.0.1", dbname, f"TRUNCATE TABLE {quoted_tables};")


def reset_pgbench_state(dbname: str, reset_mode: str) -> None:
    """Restore pgbench's logical table state before a measured row.

    pgbench's built-in TPC-B transaction mutates account, branch, and teller
    balances and appends to pgbench_history. Reset those effects before each
    row so background-level/client comparisons do not inherit state from the
    previous row. This is intentionally a logical reset, not a physical
    reinitialization, so the benchmark matrix remains practical to run.
    """
    if reset_mode == "none":
        return
    if reset_mode != "logical":
        raise ValueError(f"unsupported pgbench reset mode: {reset_mode}")

    reset_statements = [
        "TRUNCATE TABLE pgbench_history;",
        "UPDATE pgbench_accounts SET abalance = 0;",
        "UPDATE pgbench_branches SET bbalance = 0;",
        "UPDATE pgbench_tellers SET tbalance = 0;",
    ]
    for statement in reset_statements:
        psql_cmd("127.0.0.1", dbname, statement)

    # Keep planner statistics comparable after the table-wide reset.
    for table_name in (
        "pgbench_accounts",
        "pgbench_branches",
        "pgbench_tellers",
        "pgbench_history",
    ):
        psql_cmd("127.0.0.1", dbname, f"ANALYZE {table_name};")


def private_table_names(prefix: str, clients: int) -> list[str]:
    """Return the client-private foreground table names needed by one row."""
    return [f"{prefix}_{client_id:02d}" for client_id in range(clients)]


def ensure_client_private_tables(dbname: str, table_prefix: str, max_clients: int) -> None:
    """Verify that the client-private foreground tables exist and are distributed."""
    for table_name in private_table_names(table_prefix, max_clients):
        quoted = sql_literal(table_name)
        exists = psql_cmd(
            "127.0.0.1",
            dbname,
            f"SELECT to_regclass({quoted}) IS NOT NULL;",
            stdout=subprocess.PIPE,
        ).stdout.strip()
        if exists != "t":
            raise RuntimeError(
                f"expected client-private table {table_name} to exist. "
                "Run setup_citus_network_interference.py with enough --private-client-count first."
            )

        distributed = psql_cmd(
            "127.0.0.1",
            dbname,
            "SELECT count(*) FROM pg_dist_partition "
            f"WHERE logicalrelid = {quoted}::regclass;",
            stdout=subprocess.PIPE,
        ).stdout.strip()
        if int(distributed or "0") != 1:
            raise RuntimeError(f"expected client-private table {table_name} to be distributed")


def reset_client_private_tables(
    dbname: str,
    table_prefix: str,
    clients: int,
    client_private_rows: int,
    reset_mode: str,
) -> None:
    """Restore the private foreground tables touched by the low-contention workload."""
    if reset_mode == "none":
        return
    if reset_mode != "logical":
        raise ValueError(f"unsupported pgbench reset mode: {reset_mode}")

    for table_name in private_table_names(table_prefix, clients):
        quoted_table = sql_identifier(table_name)
        psql_cmd(
            "127.0.0.1",
            dbname,
            (
                f"TRUNCATE TABLE {quoted_table}; "
                f"INSERT INTO {quoted_table} (aid, abalance) "
                f"SELECT series_id, 0 FROM generate_series(1, {client_private_rows}) AS rows(series_id);"
            ),
        )
        psql_cmd("127.0.0.1", dbname, f"ANALYZE {quoted_table};")


def main() -> int:
    parser = argparse.ArgumentParser(description="Run a Citus benchmark with concurrent network traffic.")
    parser.add_argument("--dbname", default="postgres")
    parser.add_argument(
        "--modes",
        nargs="+",
        default=["local", "on", "remote_write", "remote_apply"],
        help="synchronous_commit modes to benchmark",
    )
    parser.add_argument(
        "--clients",
        type=int,
        nargs="+",
        default=[16],
        help="foreground pgbench client counts to benchmark",
    )
    parser.add_argument(
        "--repeats",
        type=int,
        default=1,
        help="number of independent repetitions for each mode/client/background row",
    )
    parser.add_argument(
        "--query-mode",
        choices=("prepared", "extended", "simple"),
        default="prepared",
        help="pgbench protocol mode to use for the foreground workload",
    )
    parser.add_argument(
        "--workload",
        choices=("client-private-table", "tpcb"),
        default="client-private-table",
        help=(
            "foreground transaction workload; client-private-table uses one "
            "single-client pgbench process per private account table"
        ),
    )
    parser.add_argument(
        "--private-table-prefix",
        default=PRIVATE_TABLE_PREFIX_DEFAULT,
        help="table prefix for the client-private-table foreground workload",
    )
    parser.add_argument(
        "--client-private-rows",
        type=int,
        default=100000,
        help="number of account rows in each client-private foreground table",
    )
    parser.add_argument("--duration", type=int, default=12)
    parser.add_argument(
        "--pgbench-workers",
        type=int,
        default=8,
        help="maximum pgbench client-side worker threads to use for -j",
    )
    parser.add_argument("--sampling-rate", type=float, default=0.05)
    parser.add_argument(
        "--background-levels",
        type=int,
        nargs="+",
        default=[0, 1, 2, 4, 8],
        help="number of background reader/writer sessions per direction; 0 means no background traffic",
    )
    parser.add_argument(
        "--background-max-sessions",
        type=int,
        default=None,
        help="number of per-session background tables precreated by setup; defaults to max(background_levels)",
    )
    parser.add_argument(
        "--background-read-prefix",
        default=BACKGROUND_READ_PREFIX_DEFAULT,
        help="prefix for the per-session background read-source tables",
    )
    parser.add_argument(
        "--background-write-prefix",
        default=BACKGROUND_WRITE_PREFIX_DEFAULT,
        help="prefix for the per-session background write-sink tables",
    )
    parser.add_argument(
        "--background-tables-logged",
        action="store_true",
        help="expect regular logged background tables instead of the default unlogged tables",
    )
    parser.add_argument(
        "--background-start-delay",
        type=float,
        default=8.0,
        help="seconds to wait before all traffic starts",
    )
    parser.add_argument(
        "--background-pad",
        type=float,
        default=10.0,
        help="extra seconds beyond the pgbench run that background traffic should continue",
    )
    parser.add_argument(
        "--writer-batch-rows",
        type=int,
        default=20000,
        help="rows per COPY batch for each background writer session",
    )
    parser.add_argument(
        "--writer-payload-bytes",
        type=int,
        default=256,
        help="payload width per row for background writer COPY batches",
    )
    parser.add_argument(
        "--results-dir",
        type=Path,
        default=REPO_ROOT / "bench-results-network-interference",
        help="directory for per-run logs and the final CSV",
    )
    parser.add_argument(
        "--csv-name",
        default=None,
        help="CSV filename inside results-dir (default: timestamped name)",
    )
    parser.add_argument(
        "--skip-setup-check",
        action="store_true",
        help="skip validation that the pgbench tables and sink table exist",
    )
    parser.add_argument(
        "--reset-pgbench-between-runs",
        choices=("logical", "none"),
        default="logical",
        help=(
            "reset foreground table side effects before each measured row; "
            "'logical' restores the selected workload's account tables"
        ),
    )
    args = parser.parse_args()

    if args.pgbench_workers < 1:
        raise SystemExit("--pgbench-workers must be at least 1")
    if any(clients < 1 for clients in args.clients):
        raise SystemExit("--clients must contain only positive integers")
    if args.repeats < 1:
        raise SystemExit("--repeats must be at least 1")
    if args.client_private_rows < 1:
        raise SystemExit("--client-private-rows must be at least 1")
    if not args.background_levels:
        raise SystemExit("--background-levels must not be empty")
    if any(level < 0 for level in args.background_levels):
        raise SystemExit("--background-levels must contain only non-negative integers")
    if not args.modes:
        raise SystemExit("--modes must not be empty")

    max_background_sessions = args.background_max_sessions
    if max_background_sessions is None:
        max_background_sessions = max(args.background_levels)
    if max_background_sessions < 1:
        raise SystemExit("--background-max-sessions must be at least 1")
    if max_background_sessions < max(args.background_levels):
        raise SystemExit(
            "--background-max-sessions must be at least as large as the maximum background level"
        )

    if not args.skip_setup_check:
        ensure_ready(
            args.dbname,
            background_read_prefix=args.background_read_prefix,
            background_write_prefix=args.background_write_prefix,
            background_max_sessions=max_background_sessions,
            background_tables_logged=args.background_tables_logged,
        )
        if args.workload == "client-private-table":
            ensure_client_private_tables(args.dbname, args.private_table_prefix, max(args.clients))

    configure_synchronous_standbys()
    reset_server_logs()

    timestamp = time.strftime("%Y%m%d-%H%M%S")
    results_dir = args.results_dir / f"citus-network-interference-{timestamp}"
    results_dir.mkdir(parents=True, exist_ok=True)

    csv_path = results_dir / (args.csv_name or "results.csv")
    fieldnames = [
        "background_level",
        "reader_sessions",
        "writer_sessions",
        "background_max_sessions",
        "background_table_persistence",
        "workload",
        "private_table_prefix",
        "client_private_rows",
        "mode",
        "query_mode",
        "clients",
        "repeat",
        "threads",
        "duration_s",
        "sampling_rate",
        "transactions_processed",
        "failed_transactions",
        "latency_avg_ms",
        "latency_stddev_ms",
        "throughput_tps",
        "sampled_transactions",
        "total_log_lines",
        "estimated_total_transactions",
        "p50_ms",
        "p95_ms",
        "p99_ms",
        "min_ms",
        "max_ms",
        "non_numeric_log_entries",
        "server_logs_dir",
        "reader_batches",
        "writer_batches",
    ]

    try:
        with csv_path.open("w", newline="", encoding="utf-8") as csv_file:
            writer = csv.DictWriter(csv_file, fieldnames=fieldnames)
            writer.writeheader()

            for mode in args.modes:
                print(f"configuring synchronous_commit={mode}", flush=True)
                set_synchronous_commit(mode)

                for clients in args.clients:
                    for level in args.background_levels:
                        for repeat in range(1, args.repeats + 1):
                            print(
                                f"running clients={clients} background level={level} repeat={repeat}",
                                flush=True,
                            )
                            # Each background session gets its own precreated table pair.
                            read_tables = background_table_names(args.background_read_prefix, max_background_sessions)[
                                :level
                            ]
                            write_tables = background_table_names(args.background_write_prefix, max_background_sessions)[
                                :level
                            ]
                            all_write_tables = background_table_names(
                                args.background_write_prefix, max_background_sessions
                            )

                            if args.workload == "tpcb":
                                reset_pgbench_state(args.dbname, args.reset_pgbench_between_runs)
                            else:
                                reset_client_private_tables(
                                    args.dbname,
                                    args.private_table_prefix,
                                    clients,
                                    args.client_private_rows,
                                    args.reset_pgbench_between_runs,
                                )
                            truncate_background_write_tables(args.dbname, all_write_tables)

                            start_at = time.monotonic() + args.background_start_delay
                            stop_at = start_at + args.duration + args.background_pad
                            barrier = threading.Barrier(level * 2 + 1)
                            failure_event = threading.Event()

                            stats: list[BackgroundStats] = []
                            threads: list[threading.Thread] = []

                            for idx in range(level):
                                reader_stats = BackgroundStats(role="reader", sessions=1)
                                writer_stats = BackgroundStats(role="writer", sessions=1)
                                stats.extend([reader_stats, writer_stats])
                                threads.append(
                                    threading.Thread(
                                        target=launch_reader_thread,
                                        kwargs={
                                            "barrier": barrier,
                                            "session_id": idx,
                                            "start_at": start_at,
                                            "stop_at": stop_at,
                                            "dbname": args.dbname,
                                            "source_table": read_tables[idx],
                                            "stats": reader_stats,
                                            "failure_event": failure_event,
                                        },
                                        daemon=True,
                                    )
                                )
                                threads.append(
                                    threading.Thread(
                                        target=launch_writer_thread,
                                        kwargs={
                                            "barrier": barrier,
                                            "session_id": idx,
                                            "start_at": start_at,
                                            "stop_at": stop_at,
                                            "dbname": args.dbname,
                                            "sink_table": write_tables[idx],
                                            "batch_rows": args.writer_batch_rows,
                                            "payload_bytes": args.writer_payload_bytes,
                                            "stats": writer_stats,
                                            "failure_event": failure_event,
                                        },
                                        daemon=True,
                                    )
                                )

                            # Start all background worker threads and wait for them to be ready.
                            for thread in threads:
                                thread.start()
                            barrier.wait()

                            run_dir = workload_run_dir(results_dir, args.workload, mode, clients, level, repeat)
                            run_dir.mkdir(parents=True, exist_ok=True)
                            snapshot_server_log_baseline(run_dir, SERVER_LOG_NODES)

                            while time.monotonic() < start_at:
                                time.sleep(min(0.5, start_at - time.monotonic()))

                            emit_row_log_marker(
                                mode=mode,
                                level=level,
                                clients=clients,
                                repeat=repeat,
                                phase="start",
                                nodes=SERVER_LOG_NODES,
                            )
                            metrics = run_pgbench(
                                clients=clients,
                                worker_threads=args.pgbench_workers,
                                duration_s=args.duration,
                                dbname=args.dbname,
                                sample_rate=args.sampling_rate,
                                mode=mode,
                                query_mode=args.query_mode,
                                workload=args.workload,
                                private_table_prefix=args.private_table_prefix,
                                client_private_rows=args.client_private_rows,
                                run_dir=run_dir,
                            )

                            for thread in threads:
                                thread.join()

                            if failure_event.is_set():
                                detail = "; ".join(
                                    err
                                    for stat in stats
                                    for err in stat.errors
                                    if err
                                )
                                raise RuntimeError(f"background traffic worker failed at level {level}: {detail}")

                            metrics["background_level"] = level
                            metrics["reader_sessions"] = level
                            metrics["writer_sessions"] = level
                            metrics["background_max_sessions"] = max_background_sessions
                            metrics["background_table_persistence"] = (
                                "logged" if args.background_tables_logged else "unlogged"
                            )
                            metrics["repeat"] = repeat
                            metrics["private_table_prefix"] = args.private_table_prefix
                            metrics["client_private_rows"] = args.client_private_rows
                            metrics["reader_batches"] = sum(stat.batches for stat in stats if stat.role == "reader")
                            metrics["writer_batches"] = sum(stat.batches for stat in stats if stat.role == "writer")
                            metrics["server_logs_dir"] = str(run_dir / "server-logs")
                            emit_row_log_marker(
                                mode=mode,
                                level=level,
                                clients=clients,
                                repeat=repeat,
                                phase="end",
                                nodes=SERVER_LOG_NODES,
                            )
                            writer.writerow(metrics)
                            csv_file.flush()
                            finalize_server_logs_for_archive(SERVER_LOG_NODES)
                            archive_server_logs(run_dir)
                            reset_server_logs()

                            truncate_background_write_tables(args.dbname, all_write_tables)

                            # Remove raw logs once the summary metrics have been parsed.
                            for log_file in run_dir.glob("pgbench_log*"):
                                if log_file.is_file():
                                    log_file.unlink()
    finally:
        try:
            set_synchronous_commit("on")
        except Exception as exc:  # pragma: no cover - cleanup path
            print(f"warning: could not restore synchronous_commit to on: {exc}", file=sys.stderr)

    print(f"results written to {csv_path}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
